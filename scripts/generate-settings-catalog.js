#!/usr/bin/env node
// Generates Sources/EufyKit/Settings/CameraSettingsCatalog.swift from eufy-security-client's published
// property catalog (npm, Apache-2.0): every per-camera setting's id, label, type and options, for the
// camera types listed below. Only the package's data module is loaded; nothing else of it runs.
//   node scripts/generate-settings-catalog.js <path to an unpacked eufy-security-client package>
//   (get one with:  npm pack eufy-security-client && tar -xzf eufy-security-client-*.tgz)
const path = require("path");
const fs = require("fs");
const pkg = process.argv[2];
if (!pkg) { console.error("usage: generate-settings-catalog.js <package dir>"); process.exit(2); }
const t = require(path.join(path.resolve(pkg), "build/http/types.js"));
const version = require(path.join(path.resolve(pkg), "package.json")).version;

// Camera device types to include (cloud device_type). Add more as cameras join the account.
const deviceTypes = { 8: "eufyCam 2C", 26: "eufyCam S3 Pro", 48: "SoloCam S340", 105: "Indoor Cam E30" };

// Not settings: live event flags, identity fields, pictures, snooze state, location, statistics.
const skip = /(detected|picture|personName|snooze|name$|model$|serialNumber|version|^type$|ringing|event|statistics|location|coordinates|address|motionZone|rtspStreamUrl)/i;

function group(name) {
  const n = name;
  const has = (re) => re.test(n);
  if (has(/^(enabled|state|antitheft)/i)) return "General";
  if (has(/notification/i)) return "Notifications";
  if (has(/(motionTracking|rotation|autoCruise|autoCalibration|roundLook|defaultAngle|dualCamWatch)/i)) return "Pan & Tilt";
  if (has(/(detection|sensitivity)/i)) return "Detection";
  if (has(/^audioRecording$/i)) return "Audio";
  if (has(/(recording|clipLength|retrigger|continuous|storeToNAS)/i)) return "Recording";
  if (has(/(microphone|speaker|volume)/i)) return "Audio";
  if (has(/(light|statusLed)/i)) return "Lights";
  if (has(/(power|battery|charging)/i)) return "Power";
  if (has(/(wifi|rtsp|cellular)/i)) return "Network";
  return "Video";
}

const str = (s) => JSON.stringify(String(s));
let out = `// Generated by scripts/generate-settings-catalog.js from eufy-security-client ${version}. Do not edit.
// swiftlint:disable all

extension CameraSettingsCatalog {
    static let generated: [Int: [CameraSetting]] = [
`;
for (const [dt, label] of Object.entries(deviceTypes)) {
  const props = Object.values(t.DeviceProperties[dt] || {});
  out += `        // ${label}\n        ${dt}: [\n`;
  for (const p of props) {
    if (typeof p.key !== "number" || !p.readable || skip.test(p.name)) continue;
    const kind = p.type === "boolean" ? ".toggle"
      : p.states ? `.choice([${Object.entries(p.states).map(([k, v]) => `(${Number(k)}, ${str(v)})`).join(", ")}])`
      : p.type === "number" ? `.number(min: ${p.min ?? "nil"}, max: ${p.max ?? "nil"}, step: ${p.steps ?? "nil"}, unit: ${p.unit ? str(p.unit) : "nil"})`
      : ".text";
    const write = typeof p.commandId === "number" && p.commandId !== p.key ? `, writeKey: ${p.commandId}` : "";
    out += `            CameraSetting(id: ${str(p.name)}, label: ${str(p.label)}, group: ${str(group(p.name))}, key: ${p.key}${write}, kind: ${kind}, writable: ${!!p.writeable}),\n`;
  }
  out += `        ],\n`;
}
out += `    ]\n}\n`;
const dest = path.join(__dirname, "..", "Sources/EufyKit/Settings/CameraSettingsCatalog.generated.swift");
fs.writeFileSync(dest, out);
console.log(`Wrote ${dest}`);
