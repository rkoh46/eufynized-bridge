#!/usr/bin/env node
// Turns captured eufy-security-client setter frames (scratch capture.js output) into Swift write recipes:
// for each camera type and setting, the frames to send for each value. Three wire forms occur:
//   int / int-string  → level-2 direct value  [u32 channel][u32 value][account id]   (outer = setting command)
//   1350 JSON envelope → level-2 SET_PAYLOAD   {"account_id","cmd","mChannel","mValue3","payload"}
//   1700 JSON          → level-2 control frame {"commandType","data"}
// Placeholders: {account}, {channel}, {transaction}, and {value} for numeric ranges.
//   node scripts/generate-settings-recipes.js captures.json
const fs = require("fs"), path = require("path");
const captures = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const CHANNEL = 7;

function frameOf(call) {
  const a = call.args[0] || {};
  if (call.method === "sendCommandWithInt" || call.method === "sendCommandWithIntString") {
    if ((a.valueSub !== undefined && a.valueSub !== CHANNEL) || (a.channel !== undefined && a.channel !== CHANNEL)) return null;
    return { form: "direct", command: a.commandType, body: String(a.value) };
  }
  if (call.method === "sendCommandWithStringPayload" && (a.commandType === 1350 || a.commandType === 1700) && a.channel === CHANNEL) {
    const body = String(a.value)
      .replace(/"ACCOUNT_ID"/g, '"{account}"')
      .replace(/"(mChannel|channel)":7(?=[,}])/g, '"$1":{channel}')
      .replace(/"transaction":"\d+"/g, '"transaction":"{transaction}"');
    if (body.includes("ACCOUNT_ID")) return null;
    return { form: a.commandType === 1350 ? "setPayload" : "control", command: a.commandType, body };
  }
  return null;
}

// App value for a captured setter value: booleans are 1/0, everything else is the number itself.
const appValue = (v) => v === true ? 1 : v === false ? 0 : Number(v);

/// If every capture differs only by its value appearing in one spot, return one {value} template.
function numericTemplate(perValue) {
  const entries = Object.entries(perValue);
  if (entries.length < 2 || entries.some(([, fs]) => fs.length !== 1)) return null;
  let template = null;
  for (const [v, [f]] of entries) {
    let t;
    if (f.form === "direct") t = f.body === v ? { ...f, body: "{value}" } : null;
    else {
      const re = new RegExp(`"(\\w+)":${v}(?=[,}])`, "g");
      const hits = [...f.body.matchAll(re)];
      t = hits.length === 1 ? { ...f, body: f.body.replace(re, '"$1":{value}') } : null;
    }
    if (!t || (template && JSON.stringify(t) !== JSON.stringify(template))) return null;
    template = t;
  }
  return template;
}

const swiftFrame = (f) => `.init(form: .${f.form}, command: ${f.command}, body: ${JSON.stringify(f.body)})`;
let out = `// Generated by scripts/generate-settings-recipes.js from eufy-security-client's own setters (captured
// against HomeBase-3-attached cameras of each type). Do not edit.
// swiftlint:disable all

extension CameraSettingsCatalog {
    static let recipes: [Int: [String: CameraSettingWriteRecipe]] = [
`;
let count = 0, skipped = [];
for (const [dt, props] of Object.entries(captures)) {
  out += `        ${dt}: [\n`;
  for (const [name, p] of Object.entries(props)) {
    const perValue = {};
    let ok = p.captures.length > 0;
    for (const cap of p.captures) {
      const frames = (cap.calls || []).map(frameOf);
      if (cap.error || frames.length === 0 || frames.includes(null)) { ok = false; break; }
      perValue[appValue(cap.value)] = frames;
    }
    if (!ok) { skipped.push(`${dt}:${name}`); continue; }
    const numeric = p.type === "number" ? numericTemplate(perValue) : null;
    const recipe = numeric
      ? `.template([${swiftFrame(numeric)}])`
      : `.perValue([${Object.entries(perValue).map(([v, fs]) => `${v}: [${fs.map(swiftFrame).join(", ")}]`).join(", ")}])`;
    out += `            ${JSON.stringify(name)}: ${recipe},\n`;
    count++;
  }
  out += `        ],\n`;
}
out += `    ]\n}\n`;
const dest = path.join(__dirname, "..", "Sources/EufyKit/Settings/CameraSettingsRecipes.generated.swift");
fs.writeFileSync(dest, out);
console.log(`Wrote ${count} recipes to ${dest}`);
console.log(`Not generated (no single safe capture): ${skipped.join(", ")}`);
